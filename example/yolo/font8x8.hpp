// Draw one glyph at (x, y) with given scale and foreground color.
// Returns the width consumed (8*scale). Unknown chars draw nothing.
// Unsupported chars are accumulated into *unsupported (or nullptr to skip).
static inline int drawGlyph(uint8_t* rgba, int W, int H,
                            char ch, int x, int y, int scale,
                            uint8_t fg_r, uint8_t fg_g, uint8_t fg_b,
                            int* unsupported = nullptr) {
    if (ch < 0 || (unsigned char)ch > 0x7F) {
        if (unsupported) *unsupported += 1;
        return 8 * scale;
    }
    const uint8_t* rows = FONT8X8[(unsigned char)ch];
    auto set_px = [&](int px, int py) {
        if (px < 0 || px >= W || py < 0 || py >= H) return;
        auto* p = rgba + (py * W + px) * 4;
        p[0] = fg_r; p[1] = fg_g; p[2] = fg_b; p[3] = 255;
    };
    for (int row = 0; row < 8; row++) {
        uint8_t bits = rows[row];
        for (int col = 0; col < 8; col++) {
            if (!(bits & (0x80 >> col))) continue;
            for (int sy = 0; sy < scale; sy++)
                for (int sx = 0; sx < scale; sx++)
                    set_px(x + col * scale + sx, y + row * scale + sy);
        }
    }
    return 8 * scale;
}

// Measure width (px) of a string at given scale (excludes background padding).
static inline int textWidth(const std::string& s, int scale) {
    return (int)s.size() * 8 * scale;
}

// Measure height (px) including background bar (8*scale).
static inline int textHeight(int scale) { return 8 * scale; }

